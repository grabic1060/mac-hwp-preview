const assert = (value, message) => { if (!value) throw new Error(message); };
const pages = document.querySelectorAll('.page');
assert(pages.length > 1, 'expected a multi-page fixture');
assert([...pages].every(p => p.querySelector('svg')?.viewBox.baseVal.height > 0), 'page dimensions');
assert(!document.querySelector('header,button,input'), 'preview must contain only document pages');
assert(!document.body.textContent.includes('실험적 미리보기'), 'preview notice removed');
const first = pages[0].getBoundingClientRect();
assert(first.top >= 0 && first.top <= 12, 'no toolbar space above document');
pages[pages.length - 1].scrollIntoView({block:'start'});
assert(window.scrollY > 0, 'last page remains reachable by scrolling');
assert(pages[pages.length - 1].textContent.length > 0, 'last page text');
window.scrollTo(0,0);
return {pages:pages.length, scrolling:true,documentOnly:true};
